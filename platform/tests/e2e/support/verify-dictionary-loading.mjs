import {chromium,expect} from '@playwright/test';
import {readFile,readdir,mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';

const base=(process.env.STUDY_TEST_BASE??'http://localhost:3210/german-learning-exam').replace(/\/$/,'');
const output=resolve('../research/lesson-expansion',process.env.STUDY_TEST_LABEL??'dictionary-export');
await mkdir(output,{recursive:true});
const chunkDir=resolve('apps/web/out/_next/static/chunks');
const files=await readdir(chunkDir);
const candidates=await Promise.all(files.filter(f=>f.endsWith('.js')).map(async f=>({file:f,text:await readFile(resolve(chunkDir,f),'utf8')})));
const chunk=candidates.find(c=>c.text.includes('office-phone-6'))?.file;
if(!chunk)throw Error('Dictionary chunk missing from export');
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:390,height:844},serviceWorkers:'block'});
const page=await context.newPage();
const checks=[],errors=[];
page.on('pageerror',e=>errors.push(e.message));
const check=label=>checks.push(label);
let blocked=true,attempts=0;
await context.route(`**/${chunk}`,route=>{attempts++;return blocked?route.abort():route.continue();});
try{
 await page.goto(base+'/cheat-sheets/office/',{waitUntil:'networkidle'});
 await expect(page.getByRole('button',{name:'Retry dictionary',exact:true})).toBeVisible();check('A failed dictionary request shows an actionable error');
 await page.getByRole('button',{name:'Open dictionary',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Quick dictionary',exact:true});
 await dialog.getByLabel('German or English',{exact:true}).fill('Kalender');
 await expect(dialog).not.toContainText('No local definition');check('Loading failure does not claim that a known word is missing');
 blocked=false;
 await dialog.getByRole('button',{name:'Try again',exact:true}).click();
 await expect(dialog.locator('article').first()).toContainText('calendar',{timeout:20000});
 await expect(dialog.locator('h3.study-tone-male').first()).toBeVisible();check('Retry loads the dictionary and the masculine card colour');
 await dialog.getByLabel('German or English',{exact:true}).fill('die Passwörter');
 await expect(dialog.locator('article').first()).toContainText('password');check('Lesson 6 irregular plural resolves to its vocabulary card');
 await dialog.getByRole('button',{name:'Close dictionary',exact:true}).click();
 await page.locator('.office-output [lang="de"]').first().evaluate(el=>{const r=document.createRange();r.selectNodeContents(el);const s=getSelection();s.removeAllRanges();s.addRange(r);document.dispatchEvent(new Event('selectionchange'));});
 await page.getByRole('button',{name:'Meaning of selection',exact:true}).click();
 await expect(dialog.locator('article').first()).toContainText('I need a calendar.');check('Selecting an entire builder sentence opens its exact meaning');
 await dialog.getByRole('button',{name:'Save to review: Ich brauche einen Kalender.',exact:true}).click();
 await expect(dialog.getByRole('button',{name:'Remove from review: Ich brauche einen Kalender.',exact:true})).toBeVisible();check('New sentence can be selected for later review');
 await dialog.getByRole('button',{name:'Close dictionary',exact:true}).click();
 const loadedAttempts=attempts;
 await expect(page.locator('#office-lab').getByRole('button',{name:'Remove from review: Ich brauche einen Kalender.',exact:true})).toBeVisible();check('Dictionary and sentence builder share the same saved item');
 await context.setOffline(true);
 await page.getByRole('button',{name:'Open dictionary',exact:true}).click();
 await dialog.getByLabel('German or English',{exact:true}).fill('Mäuse');
 await expect(dialog.locator('article').first()).toContainText('mouse');check('Loaded dictionary remains usable without a network connection');
 await dialog.getByRole('button',{name:'Close dictionary',exact:true}).click();
 await page.screenshot({path:resolve(output,'dictionary-offline-phone.png')});
 await context.setOffline(false);
 await page.locator('#office-lab').screenshot({path:resolve(output,'office-builder-phone.png')});
 await page.setViewportSize({width:1440,height:1000});
 await page.locator('#case-map').screenshot({path:resolve(output,'office-case-map.png')});
 await page.setViewportSize({width:390,height:844});
 await page.locator('.sheet-mobile-switcher summary').click();
 await page.getByRole('navigation',{name:'Choose a cheat sheet on phone'}).getByRole('link',{name:/Questions/}).click();
 await expect(page.getByRole('heading',{name:'Ask for the missing piece.',exact:true})).toBeVisible();
 if(attempts!==loadedAttempts)throw Error('Client navigation downloaded the dictionary again');check('Client navigation reuses the loaded dictionary');
 const scope=page.locator('details.study-scope');
 await scope.locator('summary').click();
 await scope.getByRole('button',{name:'One lesson',exact:true}).click();
 await scope.getByLabel('Selected lesson',{exact:true}).selectOption('6');
 await scope.locator('summary').click();
 await expect(page.getByLabel('Practice topic',{exact:true})).toHaveValue('office');
 await expect(page.locator('.question-builder-result')).toContainText('Was brauchst du?');check('Questions follow the Lesson 6 selection');
 await page.locator('#question-map').getByRole('button',{name:/Was\?/}).click();
 await page.locator('#question-word').getByRole('button',{name:'Save to review: Was bist du von Beruf?',exact:true}).click();
 await page.reload({waitUntil:'networkidle'});
 await page.locator('#question-map').getByRole('button',{name:/Was\?/}).click();
 await expect(page.locator('#question-word').getByRole('button',{name:'Remove from review: Was bist du von Beruf?',exact:true})).toBeVisible();check('A question shared across lessons stays saved after reload');
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('german-learning-os:study-book:v1')).saved['question-was']);
 if(!saved.studyTags.lessons.includes(6))throw Error('Saved question lost Lesson 6 membership');check('Saved question retains all its lesson memberships');
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw Error('Phone layout overflow');check('Dictionary and sheet fit a phone screen');
 if(errors.length)throw Error(errors.join('; '));check('No uncaught browser errors');
 await writeFile(resolve(output,'dictionary-loading.json'),JSON.stringify({base,chunk,checks,attempts,errors},null,2));
 console.log(JSON.stringify({base,passed:checks.length}));
}finally{await browser.close();}
