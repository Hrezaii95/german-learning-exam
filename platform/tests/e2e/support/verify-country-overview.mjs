import {chromium} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const base=(process.env.STUDY_TEST_BASE??'http://localhost:3210').replace(/\/$/,'');
const output=resolve('../research/country-map',process.env.STUDY_TEST_LABEL??'dev');await mkdir(output,{recursive:true});
const browser=await chromium.launch();const page=await browser.newPage({viewport:{width:1440,height:1000},serviceWorkers:'block'});page.setDefaultTimeout(15000);page.setDefaultNavigationTimeout(45000);
const checks=[],errors=[];const assert=(value,message)=>{if(!value)throw Error(message);checks.push(message);};page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto(`${base}/cheat-sheets/`,{waitUntil:'networkidle'});
 assert(await page.locator('[data-map-country]').count()===41,'Map has exactly 41 selectable study country names');
 assert(await page.locator('[data-chart-country]').count()===41,'Memory chart shows all 41 names');
 assert(await page.locator('.country-row .country-flag').count()===41,'All country index entries have flags');
 await page.locator('[data-chart-country=CH]').click();
 assert((await page.locator('.country-map-selection').innerText()).includes('aus der Schweiz'),'Flag chart selection shows the correct origin phrase');
 assert((await page.locator('.country-map-selection').getAttribute('class')).includes('study-tone-female'),'Switzerland keeps feminine color with dative der');
 assert((await page.locator('.country-passport').innerText()).includes('die Schweiz'),'Overview updates the existing sentence builder');
 await page.locator('[data-map-country=IR]').focus();await page.keyboard.press('Enter');
 assert((await page.locator('.country-map-selection').innerText()).includes('aus dem Iran'),'Map country can be selected with the keyboard');
 await page.locator('.country-map-zooms').getByRole('button',{name:'Europe',exact:true}).click();
 assert(await page.locator('.country-world-map').getAttribute('viewBox')==='445 35 165 150','Europe zoom makes small countries easier to find');
 await page.locator('[data-map-country=LI] circle').click();
 assert((await page.locator('.country-map-selection').innerText()).includes('Liechtenstein'),'Small-country marker selects its country');
 await page.locator('.country-map-zooms').getByRole('button',{name:'World',exact:true}).click();
 await page.getByRole('button',{name:'Open full-screen overview',exact:true}).click();
 assert(await page.locator('.country-atlas-dialog').evaluate(d=>d.open),'Full-screen overview opens as a dialog');
 assert(await page.locator('.country-atlas-dialog [data-chart-country]').count()===41,'Full-screen overview includes every country');
 assert(await page.locator('[data-chart-country]').count()===41,'Overview renders one interactive chart without duplicate controls');
 await page.locator('[data-chart-country=NL]').click();
 assert((await page.locator('.country-map-selection').innerText()).includes('aus den Niederlanden'),'Full-screen interaction preserves the dative plural ending');
 await page.screenshot({path:`${output}/overview-fullscreen.png`});
 await page.getByRole('button',{name:'Chart only',exact:true}).click();
 assert(await page.locator('.country-world-map').count()===0,'Chart-only mode removes the map for a compact memory view');
 await page.screenshot({path:`${output}/chart-fullscreen.png`});
 await page.keyboard.press('Escape');
 assert(await page.getByRole('button',{name:'Open full-screen overview',exact:true}).evaluate(e=>e===document.activeElement),'Closing overview restores keyboard focus');
 await page.getByRole('button',{name:'Map + chart',exact:true}).click();
 await page.locator('#country-overview').scrollIntoViewIfNeeded();
 await page.screenshot({path:`${output}/overview-desktop.png`});
 const loaded=await page.locator('.country-chart-flags img').evaluateAll(async images=>{await Promise.all(images.map(img=>img.decode()));return images.every(img=>img.naturalWidth>0);});
 assert(loaded,'Every chart flag image loads');
 await page.setViewportSize({width:390,height:844});
 await page.locator('#country-overview').scrollIntoViewIfNeeded();
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Map and chart fit the mobile viewport');
 await page.screenshot({path:`${output}/overview-mobile.png`});
 await page.getByRole('button',{name:'Chart only',exact:true}).click();
 await page.locator('[data-chart-group=female]').scrollIntoViewIfNeeded();
 await page.screenshot({path:`${output}/chart-mobile.png`});
 await page.locator('[data-chart-country=TR]').click();
 assert(await page.locator('[data-chart-country=TR]').getAttribute('aria-pressed')==='true','Mobile flag selection works');
 assert(errors.length===0,`No browser errors: ${errors.join('; ')}`);
 await writeFile(`${output}/verification.json`,JSON.stringify({base,passed:true,checks,errors},null,2));console.log(JSON.stringify({base,passed:checks.length,errors}));
}catch(error){await writeFile(`${output}/verification.json`,JSON.stringify({base,passed:false,checks,errors,error:String(error)},null,2));throw error;}finally{await browser.close();}
