import {chromium,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const base=(process.env.STUDY_TEST_BASE??'http://localhost:3210/german-learning-exam').replace(/\/$/,'');
const output=resolve('../research/lesson-expansion',process.env.STUDY_TEST_LABEL??'scope-export');
await mkdir(output,{recursive:true});
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:1000},serviceWorkers:'block'});
const checks=[],errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error'&&/hydration|React error/i.test(m.text()))errors.push(m.text());});
const check=(value,label)=>{if(!value)throw Error(label);checks.push(label);};
const visit=async(path)=>page.goto(base+path,{waitUntil:'networkidle'});
const scope=page.locator('details.study-scope');
const open=async()=>{if(!await scope.evaluate(el=>el.open))await scope.locator('summary').click();};
const one=async(n)=>{await open();await scope.getByRole('button',{name:'One lesson',exact:true}).click();await scope.getByLabel('Selected lesson',{exact:true}).selectOption(String(n));};
try{
  await visit('/vocabulary/');await one(3);
  await expect(page.locator('[data-word-family]').first()).toBeVisible();
  check(await page.locator('[data-word-family]').count()>0,'Lesson 3 vocabulary appears');
  await visit('/grammar/');
  await expect(scope.locator('summary')).toContainText('Lesson 3');
  await expect(page.getByRole('heading',{name:'Lesson 3 · grammar',exact:true})).toBeVisible();
  check(await page.locator('.course-patterns .lesson-concept').count()===9,'All nine Lesson 3 grammar concepts are in the hub');
  await visit('/');
  await expect(page.locator('[data-dashboard-lesson]')).toHaveCount(1);
  check(await page.locator('[data-dashboard-lesson]').getAttribute('data-dashboard-lesson')==='3','Dashboard follows the same lesson');
  await visit('/listening/');
  await expect(page.locator('[data-course-track]').first()).toBeVisible();
  check((await page.locator('[data-course-track]').allTextContents()).every(t=>t.includes('Lesson 3')),'Listening uses selected lesson');
  const transcript=page.locator('[data-course-track]').first().locator('details');
  await transcript.locator('summary').click();check((await transcript.innerText()).length>100,'Original listening transcript opens');
  await open();await scope.getByRole('button',{name:'Choose several',exact:true}).click();await scope.getByLabel('Lesson 4',{exact:true}).check();
  await visit('/book/');await expect(scope.locator('summary')).toContainText('Lessons 3, 4');
  await page.getByRole('button',{name:/Contents & search/}).click();
  check(await page.locator('.book-chapters button').count()===3,'Book contents has the selected chapters plus start link');
  await visit('/vocabulary/l4-stuhl/');
  const save=page.getByRole('button',{name:/Save to review:/}).first();
  await save.click();await visit('/saved/');await expect(page.getByRole('heading',{name:'My review',exact:true})).toBeVisible();
  check((await page.locator('main').innerText()).includes('Stuhl'),'Saved card remains in selected review');
  await one(1);await expect(page.locator('main')).not.toContainText('der Stuhl');
  check(true,'Changing lessons excludes the saved Lesson 4 card');
  await visit('/vocabulary/');await one(2);await scope.getByLabel('Material source').selectOption('teacher-extra');
  await expect(page.locator('[data-word-family]').first()).toBeVisible();
  check((await page.locator('[data-word-family]').allTextContents()).every(t=>t.includes('Teacher extra')),'Every teacher result is explicitly labelled');
  await one(3);await expect(page.locator('[data-word-family]')).toHaveCount(0);check(true,'Teacher extras do not leak into unrelated lessons');
  await scope.getByRole('button',{name:'Reset selection',exact:true}).click();
  await scope.getByRole('button',{name:'Up to a lesson',exact:true}).click();await scope.getByLabel('Include through',{exact:true}).selectOption('2');
  await visit('/');await expect(page.locator('[data-dashboard-lesson]')).toHaveCount(2);check(true,'Up to Lesson 2 includes both lessons');
  await open();await scope.getByRole('button',{name:'Choose several',exact:true}).click();
  await scope.getByLabel('Lesson 1',{exact:true}).uncheck();await scope.getByLabel('Lesson 2',{exact:true}).uncheck();
  await visit('/book/');await expect(page.getByText('No book pages match this selection.',{exact:false})).toBeVisible();check(true,'Empty selection stays empty after navigation');
  await page.getByRole('button',{name:'Show all book pages',exact:true}).click();await visit('/lessons/03/');
  await page.getByRole('button',{name:'Practice',exact:true}).click();
  await page.getByRole('button',{name:'meine',exact:true}).click();await expect(page.getByRole('heading',{name:'Correct!',exact:true})).toBeVisible();check(true,'Lesson 3 practice gives feedback');
  await page.screenshot({path:output+'/lesson-three-desktop.png',caret:'initial'});
  await visit('/practice/');await one(4);
  const recall=page.locator('.course-practice');
  await recall.getByRole('button',{name:'Reveal German',exact:true}).click();
  await expect(recall.locator('[lang="de"]').first()).toBeVisible();check(true,'Practice recalls vocabulary from the selected lesson');
  await recall.getByRole('button',{name:'Next card →',exact:true}).click();
  await expect(recall.getByRole('button',{name:'Reveal German',exact:true})).toBeVisible();check(true,'Next practice card hides its answer');
  await recall.getByLabel(/^Practice mode/).selectOption('article');
  await recall.getByRole('button',{name:'das',exact:true}).click();
  await expect(recall.getByText('Correct!',{exact:true})).toBeVisible();check(true,'Article practice checks the actual noun article');
  await page.setViewportSize({width:390,height:844});await visit('/vocabulary/');await one(4);
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+2),'Phone study controls fit the viewport');
  await page.screenshot({path:output+'/selection-mobile.png',caret:'initial'});
  await scope.locator('summary').click();await page.screenshot({path:output+'/vocabulary-mobile.png',caret:'initial'});
  check(errors.length===0,`No browser errors: ${errors.join('; ')}`);
  await writeFile(output+'/checks.json',JSON.stringify({base,checks,errors},null,2));
  console.log(JSON.stringify({base,passed:checks.length}));
}finally{await browser.close();}
