import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const base = (process.env.STUDY_TEST_BASE ?? 'http://127.0.0.1:4331/german-learning-exam').replace(/\/$/, '');
const output = resolve('../research/book-reader-update', process.env.STUDY_TEST_LABEL ?? 'export');
await mkdir(output, {recursive:true});
const browser = await chromium.launch({args:['--autoplay-policy=no-user-gesture-required']});
const context = await browser.newContext({viewport:{width:1440,height:1000},serviceWorkers:'block'});
const page = await context.newPage(); const checks=[], errors=[];
page.on('pageerror', error=>errors.push(error.message));
const assert=(value, message)=>{if(!value) throw Error(message); checks.push(message);};
try {
  await page.goto(`${base}/book/?page=coursebook-29`,{waitUntil:'networkidle'});
  assert(await page.locator('.book-view-page').count()===1,'Default view gives the original page its own full-width row');
  assert((await page.locator('.book-paper').boundingBox()).width>=1050,'Desktop original page is at least 1050 pixels wide');
  assert(await page.locator('.book-paper img').evaluate(img=>img.naturalWidth>=1900),'Higher-resolution page image loads');
  const transcript=page.locator('.listening-transcript').first();
  assert(!await transcript.getAttribute('open'),'Transcript is hidden until requested');
  await transcript.locator('summary').click();
  assert((await transcript.innerText()).includes('48 Euro'),'Coursebook transcript matches the picture-price dialogue');
  await transcript.getByRole('button',{name:'Look up Bild',exact:true}).first().click();
  await page.getByRole('dialog',{name:'Quick dictionary'}).waitFor();
  assert((await page.getByRole('dialog',{name:'Quick dictionary'}).innerText()).includes('picture'),'Transcript words open the dictionary');
  await page.keyboard.press('Escape');
  await transcript.locator('summary').click();
  await page.getByRole('button',{name:'Full screen ↗',exact:true}).click();
  const fullscreen=page.locator('.book-fullscreen'); await fullscreen.waitFor({state:'visible'});
  assert((await fullscreen.boundingBox()).width>=1400,'Full-screen reader uses the viewport width');
  await fullscreen.getByLabel('Page zoom',{exact:true}).selectOption('200');
  assert((await fullscreen.locator('.book-paper').boundingBox()).width>=2700,'200% zoom enlarges the actual page');
  await fullscreen.locator('.book-page-scroll').evaluate(el=>{el.scrollLeft=500;});
  assert(await fullscreen.locator('.book-page-scroll').evaluate(el=>el.scrollLeft)>100,'Enlarged page can be panned');
  await fullscreen.getByLabel('Page zoom',{exact:true}).selectOption('0');
  assert((await fullscreen.locator('.book-paper').boundingBox()).width<1440,'Fit width returns the page to the viewport');
  await page.screenshot({path:`${output}/fullscreen-desktop.png`});
  await page.keyboard.press('Escape');
  assert(!await fullscreen.isVisible(),'Escape closes full-screen reading');
  await page.getByLabel('Page zoom',{exact:true}).selectOption('100');
  await page.locator('.book-reading-tools').scrollIntoViewIfNeeded();
  await page.screenshot({path:`${output}/wide-page-desktop.png`});
  await page.setViewportSize({width:390,height:844});
  await page.goto(`${base}/book/?page=workbook-28`,{waitUntil:'networkidle'});
  assert((await page.locator('.book-paper').boundingBox()).width>=900,'Mobile starts at readable size rather than shrinking the whole page');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Mobile panning stays inside the reader');
  const all=page.locator('.listening-transcript');
  assert(await all.count()===6,'Every workbook recording on page 28 has a transcript');
  await all.nth(1).locator('summary').click();
  assert((await all.nth(1).innerText()).includes('Der Sessel kostet nur 79 Euro.'),'Workbook track matches its exercise despite shifted disc numbering');
  assert(await all.nth(1).locator('.listening-transcript-lines > p').first().evaluate(el=>parseFloat(getComputedStyle(el).fontSize))>=18,'Mobile transcript text is at least 18 pixels');
  await all.nth(1).scrollIntoViewIfNeeded();
  await page.screenshot({path:`${output}/transcript-mobile.png`});
  await page.goto(`${base}/listening/`,{waitUntil:'networkidle'});
  await page.locator('.listening-transcript').first().waitFor();
  assert(await page.locator('.listening-transcript').count()===15,'Existing listening hub also has all 15 source transcripts');
  await page.locator('.listening-transcript summary').first().click();
  assert(await page.locator('.listening-transcript-body').first().isVisible(),'Legacy listening transcript can be revealed');
  assert(errors.length===0,`No browser runtime errors: ${errors.join('; ')}`);
  await writeFile(`${output}/verification.json`,JSON.stringify({base,passed:true,checks,errors},null,2));
  console.log(JSON.stringify({base,passed:checks.length,errors}));
} catch(error) {await writeFile(`${output}/verification.json`,JSON.stringify({base,passed:false,checks,errors,failure:String(error)},null,2));throw error;}
finally {await browser.close();}
