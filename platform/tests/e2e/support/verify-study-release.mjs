import { chromium } from "@playwright/test";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const base = (process.env.STUDY_TEST_BASE ?? "http://localhost:3210").replace(/\/$/, "");
const output = resolve("../research/lesson-04-book", process.env.STUDY_TEST_LABEL ?? "local");
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ["--autoplay-policy=no-user-gesture-required"] });
const checks = [];
const errors = [];
const assert = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, serviceWorkers: "block" });
  const page = await context.newPage();
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error" && /hydration|hydrated|server rendered|React error/i.test(message.text())) errors.push(message.text()); });
  await page.goto(`${base}/lessons/04/`, { waitUntil: "networkidle" });
  await page.getByRole("heading", { name: /Das Bild/ }).waitFor();
  assert(await page.locator(".lesson-word").count() === 45, "Lesson 4 has 45 word and expression cards");
  await page.screenshot({ path: `${output}/lesson4-desktop.png`, fullPage: false });
  await page.getByRole("button", { name: "Furniture", exact: true }).click();
  assert(await page.locator(".lesson-word").count() === 12, "Furniture category filter works");
  await page.getByRole("button", { name: "Save to review: der Stuhl", exact: true }).click();
  await page.reload({ waitUntil: "networkidle" });
  assert(await page.getByRole("button", { name: "Remove from review: der Stuhl", exact: true }).count() === 1, "Word selection survives reload");
  await page.getByRole("button", { name: "Look up Stuhl", exact: true }).first().click();
  await page.getByRole("dialog").waitFor();
  assert((await page.getByRole("dialog").innerText()).includes("chair"), "One-click dictionary gives chair definition");
  await page.screenshot({ path: `${output}/dictionary.png` });
  await page.keyboard.press("Escape");
  assert(!(await page.getByRole("dialog").isVisible()), "Escape closes dictionary");
  await page.getByRole("button", { name: "Grammar", exact: true }).click();
  assert(await page.locator(".lesson-concept").count() === 5, "Five grammar concepts available");
  await page.locator(".lesson-concept").first().getByRole("button", { name: /Save to review/ }).click();
  await page.getByRole("button", { name: "Practice", exact: true }).click();
  await page.getByRole("button", { name: "das", exact: true }).click();
  assert((await page.locator(".lesson-quiz-feedback").innerText()).includes("der"), "Wrong practice answer gets correction");
  await page.getByRole("button", { name: "Next question" }).click();
  await page.getByRole("button", { name: "das", exact: true }).click();
  assert((await page.locator(".lesson-quiz-feedback").innerText()).includes("right"), "Correct practice answer gets feedback");
  await page.goto(`${base}/book/?page=coursebook-30`, { waitUntil: "networkidle" });
  await page.getByRole("heading", { name: "Your interactive book" }).waitFor();
  assert(await page.locator(".book-paper img").evaluate(img => img.complete && img.naturalWidth > 0), "Original book page renders");
  assert(await page.locator(".book-track audio").count() === 2, "Coursebook page 30 has the matching two tracks");
  await page.locator(".book-track audio").first().evaluate(async audio => { await audio.play(); });
  await page.waitForFunction(() => { const a = document.querySelector(".book-track audio"); return a && a.currentTime > .1 && !a.paused; });
  checks.push("Original publisher recording plays");
  await page.getByRole("button", { name: "Select line: Der Stuhl ist so schön", exact: false }).first().click();
  assert(await page.locator(".book-selected-line").isVisible(), "Original page line opens study controls");
  await page.locator(".book-selected-line").getByRole("button", { name: /Save to review/ }).click();
  await page.getByRole("button", { name: "☆ Bookmark", exact: true }).click();
  await page.getByRole("button", { name: "Mark page studied", exact: true }).click();
  await page.screenshot({ path: `${output}/book-desktop.png`, fullPage: false });
  await page.getByRole("button", { name: "Next page", exact: false }).click();
  await page.waitForURL(/page=coursebook-31/);
  assert(await page.locator(".book-track audio").count() === 5, "Page turn changes the original audio set");
  await page.goto(`${base}/book/`, { waitUntil: "networkidle" });
  assert((await page.locator(".book-page-toolbar").innerText()).includes("31"), "Book resumes at last page");
  await page.goto(`${base}/saved/`, { waitUntil: "networkidle" });
  await page.getByRole("heading", { name: "My review", exact: true }).waitFor();
  await page.locator(".study-saved-card").first().waitFor();
  assert(await page.locator(".study-saved-card").count() === 3, "Words, concepts and book lines share one review collection");
  await page.locator(".study-saved-card textarea").first().fill("My memory cue");
  await page.getByRole("heading", { name: "My review", exact: true }).click();
  await page.reload({ waitUntil: "networkidle" });
  assert(await page.locator(".study-saved-card textarea").first().inputValue() === "My memory cue", "Personal note survives reload");
  await page.getByRole("button", { name: /Review 3 items/ }).click();
  await page.getByRole("button", { name: "Reveal meaning", exact: true }).click();
  await page.getByRole("button", { name: "Remembered", exact: true }).click();
  assert((await page.locator(".study-recall").innerText()).includes("2 / 3"), "Recall rating advances session");
  await page.getByRole("button", { name: "End session", exact: true }).click();
  await page.getByRole("button", { name: "Remove from review: der Stuhl", exact: true }).click();
  await page.reload({ waitUntil: "networkidle" });
  assert(await page.locator(".study-saved-card").count() === 2, "Deselection survives reload");
  await page.screenshot({ path: `${output}/review-desktop.png`, fullPage: false });
  for (const route of ["/lessons/04/", "/book/?page=coursebook-29", "/saved/", "/vocabulary/l4-stuhl/"]) {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`${base}${route}`, { waitUntil: "networkidle" });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `No mobile overflow: ${route}`);
    await page.screenshot({ path: `${output}/mobile-${route.split("/")[1]}${route.includes("stuhl") ? "-stuhl" : ""}.png`, fullPage: false });
  }
  assert(errors.length === 0, `No browser runtime errors: ${errors.join("; ")}`);
  await writeFile(`${output}/verification.json`, JSON.stringify({ base, checks, errors, passed: true }, null, 2));
  console.log(JSON.stringify({ base, passed: checks.length, errors }));
} catch (error) {
  await writeFile(`${output}/verification.json`, JSON.stringify({ base, checks, errors, passed: false, failure: String(error) }, null, 2));
  throw error;
} finally { await browser.close(); }
