import { chromium } from "@playwright/test";
import { writeFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
const base = (process.env.STUDY_TEST_BASE ?? "http://localhost:3210").replace(/\/$/, "");
const output = resolve("../research/lesson-04-book", process.env.STUDY_TEST_LABEL ?? "local");
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ["--autoplay-policy=no-user-gesture-required"] });
const checks = [];
const assert = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, serviceWorkers: "block" });
  const page = await context.newPage();
  await page.goto(`${base}/book/?page=coursebook-30`, { waitUntil: "networkidle" });
  await page.getByRole("button", { name: "Page + text", exact: true }).click();
  await page.locator(".book-track audio").first().evaluate(async audio => { await audio.play(); });
  await page.waitForFunction(() => document.querySelector(".book-track audio")?.currentTime > .1);
  const tts = page.locator(".book-readable-lines .study-audio-button").filter({ hasText: "" }).nth(3);
  await tts.click();
  assert(await tts.getAttribute("aria-pressed") === "true", "Synthesized line clip starts");
  assert(await page.locator(".book-track audio").first().evaluate(a => a.paused), "Line speech stops original audio");
  await tts.click();
  assert(await tts.getAttribute("aria-pressed") === "false", "Line audio stops on second click");
  await page.getByRole("combobox", { name: /Speed/ }).selectOption("0.8");
  assert(await page.locator(".book-track audio").first().evaluate(a => a.playbackRate) === .8, "Audio speed control changes playback rate");
  await page.getByRole("button", { name: "Open dictionary", exact: true }).click();
  await page.getByLabel("German or English", { exact: true }).fill("xyznotaword123");
  assert((await page.getByRole("dialog").innerText()).includes("No local definition"), "Unknown dictionary word has an honest no-match state");
  await page.keyboard.press("Escape");
  await page.goto(`${base}/vocabulary/?lesson=04`, { waitUntil: "networkidle" });
  await page.waitForFunction(() => document.querySelectorAll("[data-word-family]").length === 45);
  assert(await page.locator("[data-word-family]").count() === 45, "Lesson 4 filter in the existing vocabulary hub returns all 45 cards");
  await page.getByRole("link", { name: "Study this word family" }).first().click();
  await page.waitForURL(/\/vocabulary\/l4-/);
  await page.waitForLoadState("networkidle");
  assert(new URL(page.url()).searchParams.get("nav")?.includes('"04"'), "Study-card navigation preserves Lesson 4 filter");
  await page.goto(`${base}/grammar/`, { waitUntil: "networkidle" });
  await page.locator("[data-hub-card=grammar] .study-save").first().click();
  await page.goto(`${base}/saved/`, { waitUntil: "networkidle" });
  await page.locator(".study-saved-card").first().waitFor();
  assert(await page.locator(".study-saved-card").count() === 1, "Earlier grammar concepts can be selected for personal review");
  await page.getByText("Backup & restore", { exact: true }).click();
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export study backup", exact: true }).click();
  const download = await downloadPromise;
  const backup = `${output}/test-backup.json`;
  await download.saveAs(backup);
  await page.locator(".study-save").first().click();
  assert(await page.locator(".study-saved-card").count() === 0, "Collection can be emptied by deselection");
  await page.locator("input[type=file]").setInputFiles(backup);
  await page.locator(".study-saved-card").first().waitFor();
  assert(await page.locator(".study-saved-card").count() === 1, "Exported backup restores selected concepts");
  await page.locator("input[type=file]").setInputFiles({ name: "bad.json", mimeType: "application/json", buffer: Buffer.from('{"version":99}') });
  await page.getByText("This file is not a supported study backup.", { exact: true }).waitFor();
  assert((await page.locator(".study-backup").innerText()).includes("not a supported study backup"), "Invalid backup is rejected");
  assert(await page.locator(".study-saved-card").count() === 1, "Invalid import preserves existing selections");
  await page.getByRole("button", { name: /Review 1 item/ }).click();
  await page.getByRole("button", { name: "Reveal meaning", exact: true }).click();
  await page.evaluate(() => { Storage.prototype.setItem = function() { throw new DOMException("Full", "QuotaExceededError"); }; });
  await page.getByRole("button", { name: "Remembered", exact: true }).click();
  assert(await page.getByRole("button", { name: "Remembered", exact: true }).count() === 1 && await page.locator(".study-recall-finish").count() === 0, "Failed recall save does not advance or lose the current card");
  const restricted = await browser.newContext({ serviceWorkers: "block" });
  await restricted.addInitScript(() => { Storage.prototype.setItem = function() { throw new DOMException("Full", "QuotaExceededError"); }; });
  const denied = await restricted.newPage();
  await denied.goto(`${base}/lessons/04/`, { waitUntil: "networkidle" });
  await denied.getByRole("button", { name: "Save to review: der Stuhl", exact: true }).click();
  assert((await denied.locator(".study-storage-error").innerText()).includes("could not be saved"), "Storage failure is visible");
  assert(await denied.getByRole("button", { name: "Save to review: der Stuhl", exact: true }).count() === 1, "Failed save is not shown as saved");
  await writeFile(`${output}/edgecases.json`, JSON.stringify({ base, passed: true, checks }, null, 2));
  console.log(JSON.stringify({ base, passed: checks.length }));
} catch (error) { await writeFile(`${output}/edgecases.json`, JSON.stringify({ base, passed: false, checks, error: String(error) }, null, 2)); throw error; }
finally { await browser.close(); }
