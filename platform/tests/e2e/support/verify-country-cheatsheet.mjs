import {chromium} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const base=(process.env.STUDY_TEST_BASE??'http://localhost:3210').replace(/\/$/,'');
const output=resolve('../research/country-cheatsheet',process.env.STUDY_TEST_LABEL??'dev');
await mkdir(output,{recursive:true});
const browser=await chromium.launch({args:['--autoplay-policy=no-user-gesture-required']});
const page=await browser.newPage({viewport:{width:1440,height:1000},serviceWorkers:'block'});
page.setDefaultTimeout(15000);page.setDefaultNavigationTimeout(45000);
const checks=[],errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>{const original=HTMLMediaElement.prototype.play;HTMLMediaElement.prototype.play=function(){window.__countryAudio=this;return original.call(this);};});
const assert=(condition,message)=>{if(!condition)throw Error(message);checks.push(message);};
const rows=page.locator('[data-country]');
try{
  await page.goto(`${base}/cheat-sheets/`,{waitUntil:'networkidle'});
  assert(await rows.count()===41,'All 41 country names render');
  assert(await page.locator('.country-gate').count()===4,'Four color-coded article paths are visible');
  assert((await page.locator('.country-passport').innerText()).includes('Ich komme aus dem Iran.'),'Sentence builder opens with Iran');
  assert((await page.locator('.country-memory-notes').innerText()).includes('aus Iran · in Iran · nach Iran'),'Article-free Iran alternative is explained');
  await page.screenshot({path:`${output}/overview-desktop.png`});
  await page.locator('.country-passport .study-audio-button').first().click();
  await page.waitForFunction(()=>window.__countryAudio?.currentTime>.1);
  assert(await page.evaluate(()=>window.__countryAudio.currentSrc.includes('/audio/')),'Country sentence audio loads and plays');
  await page.getByLabel('Choose a country',{exact:true}).selectOption('NL');
  assert((await page.locator('.country-passport').innerText()).includes('aus den Niederlanden'),'Builder adds the dative plural ending');
  assert((await page.locator('.country-memory-notes').innerText()).includes('in die Niederlande'),'Destination uses the accusative country form');
  await page.getByLabel('Choose a country',{exact:true}).selectOption('CH');
  assert((await page.locator('[data-country=CH] .country-languages').innerText()).includes('Rätoromanisch'),'Switzerland includes all four national languages');
  await page.getByLabel('Choose a country',{exact:true}).selectOption('IR');
  await page.locator('#country-passport').scrollIntoViewIfNeeded();
  await page.screenshot({path:`${output}/passport-desktop.png`});
  await page.getByLabel('Find a country or language',{exact:true}).fill('Iran');
  assert(await rows.count()===1,'Country search narrows the index');
  const save=rows.first().getByRole('button',{name:'Save to review: Ich komme aus dem Iran.',exact:true});
  await save.click();
  await page.reload({waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Saved for review',exact:true}).click();
  assert(await rows.count()===1,'Saved country survives reload and has its own filter');
  await rows.first().getByRole('button',{name:'Remove from review: Ich komme aus dem Iran.',exact:true}).click();
  assert(await rows.count()===0,'Country can be deselected from review');
  await page.getByRole('button',{name:'All patterns',exact:true}).click();
  await page.getByLabel('Book coverage',{exact:true}).selectOption('core');
  assert(await rows.count()===28,'Core coverage includes every existing country card');
  await page.getByLabel('Book coverage',{exact:true}).selectOption('all');
  await page.getByRole('button',{name:'Plural · die',exact:true}).click();
  assert(await rows.count()===3,'Plural filter includes USA, Netherlands, and Maldives');
  await page.getByRole('button',{name:'Feminine · die',exact:true}).click();
  assert(await rows.count()===2,'Feminine filter includes Switzerland and Turkey');
  await page.getByRole('button',{name:'All patterns',exact:true}).click();
  await page.getByRole('button',{name:'Hide answers & recall',exact:true}).click();
  const netherlands=page.locator('[data-country=NL]');
  assert(!(await netherlands.innerText()).includes('aus den Niederlanden'),'Recall hides the answer before reveal');
  await netherlands.getByRole('button',{name:'Reveal Niederlande',exact:true}).click();
  assert((await netherlands.innerText()).includes('aus den Niederlanden'),'Individual reveal shows the correct form');
  await page.getByRole('button',{name:'Show all answers',exact:true}).click();
  await page.locator('[data-country=IR]').getByRole('button',{name:'Look up Iran',exact:true}).first().click();
  const dictionary=page.getByRole('dialog',{name:'Quick dictionary'});await dictionary.waitFor();
  assert((await dictionary.innerText()).includes('Masculine'),'Country word lookup preserves its grammatical gender');
  await page.keyboard.press('Escape');
  await page.locator('#country-practice').scrollIntoViewIfNeeded();
  await page.getByRole('button',{name:'aus der Iran',exact:true}).click();
  assert((await page.locator('.country-quiz-feedback').innerText()).includes('Almost.'),'Wrong answers receive an explanation');
  await page.getByRole('button',{name:'Next →',exact:true}).click();
  for(const answer of ['aus der Schweiz','aus den USA','aus den Niederlanden','aus Deutschland','aus Polen','aus der Türkei','aus den Malediven','Persisch','Deutsch']){
    await page.locator('.country-quiz-options').getByRole('button',{name:answer,exact:true}).click();
    await page.getByRole('button',{name:'Next →',exact:true}).click();
  }
  assert((await page.locator('.country-quiz').innerText()).includes('9 / 10'),'Quiz score records answers once');
  await page.getByRole('button',{name:'Practise again',exact:true}).click();
  await page.getByRole('button',{name:'aus Iran',exact:true}).click();
  assert((await page.locator('.country-quiz-feedback').innerText()).includes('Yes — that works.'),'Quiz accepts the article-free Iran variant');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#country-patterns').scrollIntoViewIfNeeded();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Mobile page has no horizontal overflow');
  await page.screenshot({path:`${output}/patterns-mobile.png`});
  await page.locator('#country-passport').scrollIntoViewIfNeeded();
  await page.screenshot({path:`${output}/passport-mobile.png`});
  await page.getByLabel('Find a country or language',{exact:true}).fill('Schweiz');
  await page.locator('[data-country=CH]').scrollIntoViewIfNeeded();
  assert((await rows.innerText()).includes('aus der Schweiz'),'Mobile country card keeps the article and language readable');
  await page.screenshot({path:`${output}/index-mobile.png`});
  await page.getByRole('button',{name:'Hide answers & recall',exact:true}).click();
  await page.evaluate(()=>{window.print=()=>{window.__printed=true;};});
  await page.getByRole('button',{name:'Print cheat sheet',exact:true}).click();
  await page.waitForFunction(()=>window.__printed);
  assert(await rows.count()===41,'Printing restores the complete country index');
  assert(await page.getByRole('button',{name:'Hide answers & recall',exact:true}).count()===1,'Printing reveals the answers');
  await page.setViewportSize({width:1440,height:1000});
  await page.pdf({path:`${output}/country-cheat-sheet.pdf`,format:'A4',printBackground:true,margin:{top:'10mm',bottom:'12mm',left:'10mm',right:'10mm'}});
  await page.goto(`${base}/hubs/`,{waitUntil:'networkidle'});
  assert(await page.locator('.country-hub-link').count()===1,'Cheat sheet is reachable from mobile Hubs');
  await page.locator('.country-hub-link').click();await page.waitForURL(/\/cheat-sheets\/?$/);
  assert(await rows.count()===41,'Hubs link opens the complete cheat sheet');
  assert(errors.length===0,`No browser errors: ${errors.join('; ')}`);
  await writeFile(`${output}/verification.json`,JSON.stringify({base,passed:true,checks,errors},null,2));
  console.log(JSON.stringify({base,passed:checks.length,errors}));
}catch(error){await writeFile(`${output}/verification.json`,JSON.stringify({base,passed:false,checks,errors,failure:String(error)},null,2));throw error;}
finally{await browser.close();}
